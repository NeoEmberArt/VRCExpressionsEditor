using System.Collections.Generic;
using System.Linq;
using System.IO;
using System.Text.RegularExpressions;
using UnityEngine;
using UnityEditor;
using VRC.SDK3.Avatars.Components;
using VRC.SDK3.Avatars.ScriptableObjects;

public partial class EASYExpressionManager
{

    bool NodeHasDeletableSource(ExpressionNode n)
    {
        if (n == null || n == root) return false;
        if (n.sourceControl != null && n.sourceMenu != null) return true;
        if (n.sourceObject != null) return true;
        if (n.isFromFullController && n.sourceFullControllerObject != null) return true;
        if (n.isVirtualFolder || IsRegisteredVirtualPath(PathOf(n))) return true;
        if (n.isFCPrefixFolder && n.fcPrefixGenerators.Count > 0) return true;
        if (n.isMoveGeneratedFolder && n.moveGenerators.Count > 0) return true;
        // a plain folder is deletable when anything inside it is
        return n.children.Any(NodeHasDeletableSource);
    }

    /// True for a single item whose delete removes exactly its own backing
    /// object (a Fury toggle component, a native control, a Full Controller
    /// control) — no path lookup involved.
    bool DeletesByOwnObject(ExpressionNode n) =>
        n != null && n.children.Count == 0 &&
        (n.sourceObject != null ||
         (n.sourceControl != null && n.sourceMenu != null && !n.isFromFullController) ||
         (n.isFromFullController && n.sourceControl != null));

    int CountDeletableDescendants(ExpressionNode n) =>
        CollectAllDescendants(n).Count(NodeHasDeletableSource);

    void ConfirmAndDelete(ExpressionNode n)
    {
        if (n == null || n == root) return;
        n = ResolveLiveNode(n);
        if (n == null)
        {
            EditorUtility.DisplayDialog("Can't delete", "The selected item changed or was removed. Rescan before deleting it.", "OK");
            return;
        }

        // Deleting sweeps move/icon records by PATH STRING (RemoveMoveRecordsTouching,
        // RemoveIconOverridesTouching below) — if this node's path is shared with
        // a duplicate sibling, that sweep can't tell them apart and would strip
        // records that actually belong to the other one. Refuse up front rather
        // than let the confirm dialog promise something the delete can't
        // safely deliver.
        //
        // Also refuse if a Full Controller entry under this path isn't
        // accounted for by anything we're about to clean up — that's exactly
        // how a delete can destroy real content (toggles, controls) while the
        // folder itself survives as an empty shell, regenerated by the
        // leftover entry, reporting an OUTCOME MISMATCH that undersells how
        // much was actually lost.
        try
        {
            // A single item removed through its own object can't hit a
            // same-name neighbour; anything else is found by path.
            if (!DeletesByOwnObject(n)) GuardUnambiguousPath(PathOf(n, n.IsFolderLike), "delete");
            GuardNoOrphanShell(n);
        }
        catch (System.Exception ex)
        {
            EditorUtility.DisplayDialog("Can't delete", ex.Message, "OK");
            return;
        }

        if (!ConfirmDeleteRisk(n)) return;

        string displayName = DisplayOf(n);
        int inside = CountDeletableDescendants(n);
        string msg = inside > 0
            ? $"Removes \"{displayName}\" and the {inside} item(s) inside it.\n\nUndo with Ctrl+Z."
            : $"Removes \"{displayName}\".\n\nUndo with Ctrl+Z.";
        if (!EditorUtility.DisplayDialog($"Delete \"{displayName}\"?", msg, "Delete", "Cancel")) return;

        SnapshotExpansionStates(root);
        Undo.IncrementCurrentGroup();
        Undo.SetCurrentGroupName($"Delete \"{displayName}\"");
        int undoGroup = Undo.GetCurrentGroup();
        string logPath = PathOf(n);
        var priorDangling = new List<string>(danglingRecordDescriptions);
        LogOp("Delete", logPath, n.type.ToString(), logPath, "", () =>
        {
            DeleteNode(n);
            QueueRescan();
        }, new Dictionary<string, object>
        {
            ["sourceCategory"] = SourceCategoryOf(n),
            ["expectedDeleteCounts"] = new List<object> { new Dictionary<string, object>
            {
                ["path"] = logPath,
                ["maximumCount"] = System.Math.Max(0, FindAllNodesAtPath(root, logPath).Count - 1),
            } },
        });
        Undo.CollapseUndoOperations(undoGroup);
        FlushRescan();
        OfferCleanupIfNewDanglingRecords(priorDangling);
        if (selected == n) selected = null;
        Repaint();
    }

    /// Deleting a properly-chained record's own destination already prunes it
    /// automatically (RemoveMoveRecordsTouching runs for every node visited
    /// during the recursive delete). What this catches is different: records
    /// that were ALREADY broken before this delete — historical debris this
    /// tool can't safely auto-remove without asking — surfaced immediately
    /// instead of waiting for the user to separately notice the toolbar badge.
    void OfferCleanupIfNewDanglingRecords(List<string> before)
    {
        var newOnes = danglingRecordDescriptions.Except(before).ToList();
        if (newOnes.Count == 0) return;
        Debug.LogWarning($"[EASY] This delete left {newOnes.Count} Move Menu Item record(s) pointing at nothing:\n- " +
                         string.Join("\n- ", newOnes));
        if (EditorUtility.DisplayDialog("Clean up leftover records?",
            $"This delete left {newOnes.Count} move record(s) that no longer point at anything:\n\n" +
            string.Join("\n", newOnes.Take(8)) + (newOnes.Count > 8 ? $"\n…and {newOnes.Count - 8} more" : "") +
            "\n\nClean them up now?",
            "Clean Up Now", "Leave Them"))
            CleanUpRecordsInteractive();
    }

    bool HasRelocatedSourceOutside(ExpressionNode folder)
    {
        if (folder == null || !folder.IsFolderLike) return false;
        var nativeRoots = new List<string>();
        void CollectRoots(ExpressionNode source)
        {
            if (!string.IsNullOrEmpty(source.nativePath)) nativeRoots.Add(source.nativePath);
            foreach (var merged in source.mergedSources) CollectRoots(merged);
        }
        CollectRoots(folder);
        bool UsesSource(ExpressionNode candidate)
        {
            if (candidate.nativePath != null && nativeRoots.Any(path => EEMPath.IsUnder(candidate.nativePath, path))) return true;
            return candidate.mergedSources.Any(UsesSource);
        }
        return allNodesFlatList.Any(candidate => candidate != folder && !IsAncestorOf(folder, candidate) && UsesSource(candidate));
    }

    bool DeletesBackingSubtree(ExpressionNode folder)
    {
        var submenu = folder?.sourceControl?.subMenu;
        if (!submenu || folder.mergedSources.Count > 0) return false;
        var menus = new HashSet<VRCExpressionsMenu>(CaptureFCControlArrays(new[] { submenu }).Keys);
        bool IsOwnSource(ExpressionNode node)
        {
            if (node.isVirtualFolder || node.isFCPrefixFolder || node.sourceObject != null || node.mergedSources.Count > 0 ||
                node.sourceControl == null || node.isFromFullController != folder.isFromFullController) return false;
            if (folder.isFromFullController)
            {
                if (node.sourceFullControllerObject?.targetObject != folder.sourceFullControllerObject?.targetObject ||
                    node.fcEntryIndex != folder.fcEntryIndex || !menus.Contains(node.sourceFullControllerMenu)) return false;
            }
            else if (!menus.Contains(node.sourceMenu)) return false;
            return node.children.All(IsOwnSource);
        }
        return folder.children.All(IsOwnSource);
    }

    void DeleteNode(ExpressionNode n)
    {
        if (n == null || n == root) return;
        n = ResolveLiveNode(n);
        if (n == null) throw new System.InvalidOperationException("The selected item changed or was removed before deletion. Rescan before editing it.");
        string path = PathOf(n);

        // Moved controls still build from their original backing menus and
        // prefixes. Destroying this source folder would destroy those controls
        // at their new destinations too. Keep the source route and remove this
        // displayed subtree after its outgoing moves have run.
        if (HasRelocatedSourceOutside(n))
        {
            CommitMove(path, "", n);
            if (n.sameNameCount <= 1) RemoveIconOverridesTouching(path);
            NoteConsequence("kept backing sources for relocated items; deleted the displayed folder through a MoveMenuItem record");
            return;
        }

        // Removing a submenu link removes its complete backing subtree.
        // Shared or cyclic submenu assets must not have their controls removed
        // once per branch before removing the link itself.
        if (!DeletesBackingSubtree(n))
            foreach (var child in n.children.ToArray()) DeleteNode(child);

        // ── the node's own backing object ─────────────────────────────────────
        if (n.sourceObject != null) DeleteVRCFuryToggleComponent(n);
        else if (n.sourceControl != null && n.sourceMenu != null && !n.isFromFullController) DeleteVRCControl(n);
        else if (n.isFromFullController && n.sourceControl != null) DeleteFCControl(n);

        // ── and everything that would re-create it ────────────────────────────
        if (n.isVirtualFolder || IsRegisteredVirtualPath(path))
        {
            RemoveVirtualFolder(path);
            if (!string.IsNullOrEmpty(n.virtualPath)) RemoveVirtualFolder(n.virtualPath);
        }
        if (n.isFCPrefixFolder) DeleteFCEntriesForPrefixFolder(n);
        foreach (var source in n.mergedSources) DeleteMergedBacking(source);
        // Records are matched by path — while a same-name neighbour remains,
        // they belong to it too, so leave them alone.
        if (n.sameNameCount <= 1)
        {
            RemoveMoveRecordsTouching(path);
            RemoveIconOverridesTouching(path);
        }
    }

    void DeleteMergedBacking(ExpressionNode n)
    {
        if (n.sourceObject != null) DeleteVRCFuryToggleComponent(n);
        else if (n.sourceControl != null && n.sourceMenu != null && !n.isFromFullController) DeleteVRCControl(n);
        else if (n.isFromFullController && n.sourceControl != null) DeleteFCControl(n);
        if (n.isFCPrefixFolder) DeleteFCEntriesForPrefixFolder(n);
        foreach (var source in n.mergedSources) DeleteMergedBacking(source);
    }

    void DeleteVRCControl(ExpressionNode n)
    {
        var menu = EnsureWritableNativeMenu(n);
        if (!menu) throw new System.InvalidOperationException("The native menu could not be made writable; delete was cancelled.");
        Undo.RecordObject(menu, $"Delete VRC Control \"{DisplayOf(n)}\"");
        var wanted = n.sourceControl;
        if (wanted == null) throw new System.InvalidOperationException("The native control no longer exists; rescan before deleting it.");
        if (!menu.controls.Contains(wanted))
        {
            // Deserialization can replace a native control too. Never remove
            // every same-named peer as a fallback, especially blank controls.
            bool oldControlSurvives = n.parent != null && n.parent.children.Any(sibling =>
                sibling.sourceMenu == menu && sibling.sourceControl != null && menu.controls.Contains(sibling.sourceControl));
            int index = -1;
            string sourceKey = n.sourceKey ?? "";
            bool samePosition = !oldControlSurvives && menu.controls.Count == n.sourceControlCount &&
                int.TryParse(sourceKey.Substring(sourceKey.LastIndexOf(':') + 1), out index) &&
                index >= 0 && index < menu.controls.Count && menu.controls[index] != null &&
                JsonUtility.ToJson(menu.controls[index]) == JsonUtility.ToJson(wanted);
            if (!samePosition)
                throw new System.InvalidOperationException("This native menu control changed during the operation; rescan before deleting it.");
            wanted = menu.controls[index];
        }
        menu.controls.Remove(wanted);
        EditorUtility.SetDirty(menu);
    }

    void DeleteVRCFuryToggleComponent(ExpressionNode n)
    {
        if (n.sourceObject?.targetObject == null)
            throw new System.InvalidOperationException("The VRCFury component no longer exists; rescan before deleting it.");
        var comp = n.sourceObject.targetObject as Component;
        if (!comp) throw new System.InvalidOperationException("The VRCFury delete target is not a component.");

        Undo.DestroyObjectImmediate(comp);
    }

    /// Removes a control from a Full Controller menu — via a project-owned copy,
    /// so the package asset is left alone.
    void DeleteFCControl(ExpressionNode n)
    {
        var writable = EnsureWritableFCMenu(n, out int idx);
        if (writable == null || idx < 0 || idx >= writable.controls.Count)
            throw new System.InvalidOperationException("The Full Controller control could not be made writable; delete was cancelled.");
        Undo.RecordObject(writable, $"Delete FC Control \"{DisplayOf(n)}\"");
        writable.controls.RemoveAt(idx);
        EditorUtility.SetDirty(writable);
    }

    /// Deletes the Full Controller menu entries that produce this prefix folder.
    /// This is what makes the "Emotes → MOTION" ghost folder removable.
    ///
    /// A single folder can be produced by entries on SEVERAL DIFFERENT VRCFury
    /// components at once — e.g. one component owns "Setting/autoSet", another
    /// owns "Setting/soundFX", a third owns bare "Setting" for one direct
    /// toggle. Cleaning up only the first owner the scan happened to record
    /// left the other components' entries — and everything under them —
    /// completely untouched, so the folder came back as an empty shell after
    /// what looked like a successful delete. This groups by owner and cleans
    /// up every one of them.
    ///
    /// Entries are matched by their stored prefix VALUE, not by the array index
    /// captured during the scan: deleting a folder recurses into its children
    /// first, and each removal shifts every later index, so index-based deletion
    /// would remove an unrelated entry on the way back up.
    void DeleteFCEntriesForPrefixFolder(ExpressionNode n)
    {
        if (n.fcPrefixGenerators.Count == 0) return;

        var byOwner = n.fcPrefixGenerators
            .Where(g => g.owner?.targetObject != null)
            .GroupBy(g => g.owner.targetObject);

        foreach (var group in byOwner)
        {
            var comp = group.Key as Component;
            if (!comp) continue;


            var so = new SerializedObject(comp); so.Update();
            var menusProp = so.FindProperty("content.menus");
            if (menusProp == null || !menusProp.isArray) continue;

            var wanted = new HashSet<string>(group.Select(g => g.prefix), System.StringComparer.Ordinal);
            var doomed = new List<int>();
            for (int i = 0; i < menusProp.arraySize; i++)
            {
                string prefix = menusProp.GetArrayElementAtIndex(i).FindPropertyRelative("prefix")?.stringValue ?? "";
                if (wanted.Contains(prefix)) doomed.Add(i);
            }
            if (doomed.Count == 0)
            {
                Debug.Log($"[EASY] No matching entries left on '{comp.name}' for \"{DisplayOf(n)}\" — " +
                         "already removed by a child folder's own cleanup.");
                continue;
            }

            Undo.RecordObject(comp, $"Delete Full Controller menu entries under \"{DisplayOf(n)}\"");
            foreach (int idx in doomed.OrderByDescending(i => i)) menusProp.DeleteArrayElementAtIndex(idx);
            so.ApplyModifiedProperties();
            EditorUtility.SetDirty(comp);
            Debug.Log($"[EASY] Removed {doomed.Count} Full Controller menu entr{(doomed.Count == 1 ? "y" : "ies")} " +
                     $"for \"{DisplayOf(n)}\" from '{comp.name}'.");
            NoteConsequence($"removed {doomed.Count} FC entr{(doomed.Count == 1 ? "y" : "ies")} on '{comp.name}'");

            // The component is deliberately left in place even with no menu
            // entries left: a Full Controller also carries animator layers and
            // parameters, and destroying it to tidy up an empty array would
            // silently strip those from the avatar.
        }
    }

    // ═══════════════════════════════════════════════════════════════════════════
    // ORPHAN-SHELL DETECTION
    //
    // DeleteFCEntriesForPrefixFolder only knows about generators the SCAN found
    // and attached to this node. If the scan itself missed something — a stale
    // reference, a component added after the last scan, or simply a bug in the
    // walk — the delete would still report success while leaving a live entry
    // (and everything under it) behind, regenerating the folder as an empty
    // shell after real content was already destroyed. This does an independent,
    // from-scratch check across every VRCFury component in the avatar, so it
    // catches gaps that don't depend on this node's own bookkeeping being right.
    // ═══════════════════════════════════════════════════════════════════════════

    /// Every (component, prefix) pair anywhere on the avatar whose prefix is
    /// at-or-under the given internal path — a ground-truth answer to "what
    /// would regenerate a folder at this path", independent of anything the
    /// tree/scan already believes about it.
    List<(Component comp, string prefix)> FindAllFCPrefixesUnder(string internalPath)
    {
        var result = new List<(Component, string)>();
        if (!avatar) return result;
        foreach (var comp in avatar.GetComponentsInChildren<Component>(true))
        {
            if (!comp || comp is Transform) continue;
            string fn = comp.GetType().FullName ?? "";
            if (!fn.Contains("VRCFury") && !fn.Contains("VF.")) continue;
            var so = new SerializedObject(comp);
            var menusProp = so.FindProperty("content.menus");
            if (menusProp == null || !menusProp.isArray) continue;
            for (int i = 0; i < menusProp.arraySize; i++)
            {
                string prefix = menusProp.GetArrayElementAtIndex(i).FindPropertyRelative("prefix")?.stringValue ?? "";
                if (string.IsNullOrEmpty(prefix)) continue;
                string prefixInternal = EEMPath.FromVrcf(prefix);
                if (EEMPath.IsAtOrUnder(prefixInternal, internalPath))
                    result.Add((comp, prefix));
            }
        }
        return result;
    }

    /// Refuses to delete a folder if doing so would leave real content behind
    /// disguised as a harmless "regenerated container". Compares a fresh,
    /// independent scan of every FC component's prefix entries against what
    /// this node's (and its descendants') own tracked generators would
    /// actually clean up — if the live scan finds something the planned
    /// cleanup doesn't cover, that's exactly the failure mode this guards
    /// against, so it refuses before anything is deleted rather than after.
    void GuardNoOrphanShell(ExpressionNode n)
    {
        if (n == null || n == root) return;
        string path = PathOf(n);

        var liveEntries = FindAllFCPrefixesUnder(path);
        if (liveEntries.Count == 0) return;   // nothing FC-prefix-generated here at all

        var covered = new HashSet<(Object, string)>();
        void CollectCoverage(ExpressionNode node)
        {
            foreach (var g in node.fcPrefixGenerators)
                if (g.owner?.targetObject != null) covered.Add((g.owner.targetObject, g.prefix));
            foreach (var c in node.children) CollectCoverage(c);
        }
        CollectCoverage(n);

        var uncovered = liveEntries.Where(e => !covered.Contains((e.comp, e.prefix))).ToList();
        if (uncovered.Count == 0) return;

        string list = string.Join(", ", uncovered.Select(e => $"'{e.prefix}' on {e.comp.name}"));
        Debug.LogError($"[EASY] Refused to delete \"{DisplayOf(n)}\": found {uncovered.Count} Full Controller " +
                       $"entr{(uncovered.Count == 1 ? "y" : "ies")} under this path that the delete wouldn't have " +
                       $"cleaned up ({list}). Deleting anyway would remove everything the tool DOES track and " +
                       "leave this folder behind as an empty shell, still holding whatever those entries produce.");
        throw new System.InvalidOperationException(
            $"Can't delete \"{DisplayOf(n)}\": {uncovered.Count} Full Controller entr{(uncovered.Count == 1 ? "y" : "ies")} " +
            $"under this path ({list}) aren't accounted for and would survive the delete, regenerating this folder " +
            "with whatever they produce still inside it. Rescan and try again, or check those components directly.");
    }

    // ═══════════════════════════════════════════════════════════════════════════
    // DELETE RISK ASSESSMENT
    //
    // GuardNoOrphanShell already guarantees a delete won't leave a live entry
    // behind unaccounted for. What it does NOT protect against is the user not
    // realising how much is about to be destroyed — a folder fed by many
    // components, or one that happens to now contain content the user
    // specifically moved there, is easy to underestimate from the tree alone.
    // This surfaces that risk explicitly, before anything is touched.
    // ═══════════════════════════════════════════════════════════════════════════

    /// Every distinct component contributing to this folder or any nested
    /// prefix folder inside it.
    int CountDistinctFCComponents(ExpressionNode n)
    {
        var owners = new HashSet<Object>();
        void Walk(ExpressionNode node)
        {
            foreach (var g in node.fcPrefixGenerators)
                if (g.owner?.targetObject != null) owners.Add(g.owner.targetObject);
            foreach (var c in node.children) Walk(c);
        }
        Walk(n);
        return owners.Count;
    }

    /// Descendants that arrived here via a Move Menu Item record rather than
    /// being natively/originally produced by this folder's own components —
    /// content the user specifically relocated, which a cascade-delete would
    /// otherwise destroy without any distinction from the folder's own
    /// original contents.
    List<ExpressionNode> FindRelocatedDescendants(ExpressionNode n)
    {
        var result = new List<ExpressionNode>();
        void Walk(ExpressionNode node)
        {
            if (node.hasManagedMove) result.Add(node);
            foreach (var c in node.children) Walk(c);
        }
        foreach (var c in n.children) Walk(c);
        return result;
    }

    /// Blocks with an explicit, detailed confirmation when deleting this node
    /// carries risk a generic "Delete X?" dialog wouldn't convey — multiple
    /// components feeding the same folder, or content the user relocated here
    /// on purpose. Returns true if it's safe to proceed (either no risk, or the
    /// user explicitly acknowledged it); false if the user backed out.
    bool ConfirmDeleteRisk(ExpressionNode n)
    {
        int componentCount = CountDistinctFCComponents(n);
        var relocated = FindRelocatedDescendants(n);

        bool multiComponent = componentCount > 1;
        bool hasRelocated = relocated.Count > 0;
        if (!multiComponent && !hasRelocated) return true;   // nothing unusual — normal confirm dialog handles it

        var lines = new List<string>();
        if (multiComponent)
            lines.Add($"• Fed by {componentCount} different Full Controller components at once — " +
                     "deleting it removes entries on all of them.");
        if (hasRelocated)
            lines.Add($"• Contains {relocated.Count} item(s) moved here from elsewhere, not originally part of " +
                     $"this folder: {string.Join(", ", relocated.Take(6).Select(DisplayOf))}" +
                     (relocated.Count > 6 ? $", and {relocated.Count - 6} more" : "") +
                     ". Deleting \"" + DisplayOf(n) + "\" destroys these too, not just its native contents.");

        Debug.LogWarning($"[EASY] Delete risk on \"{DisplayOf(n)}\": " + string.Join(" ", lines));

        return EditorUtility.DisplayDialog(
            $"\"{DisplayOf(n)}\" carries extra risk",
            string.Join("\n\n", lines) + "\n\nMove the relocated item(s) out first if you want to keep them, " +
            "or continue to delete everything.",
            "Delete Anyway", "Cancel");
    }

}
