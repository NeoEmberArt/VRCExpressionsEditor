// Easy Expression Manager: verify operation outcomes and describe surviving menu generators.

using System.Collections.Generic;
using System.Linq;
using System.IO;
using UnityEngine;
using UnityEditor;

public partial class EASYExpressionManager
{
    // ═══════════════════════════════════════════════════════════════════════════
    // POST-CONDITION CHECKS
    // ═══════════════════════════════════════════════════════════════════════════

    void VerifyExpectedOutcome(string opType, string targetPath, string oldValue, string newValue,
                                Dictionary<string, object> context, List<object> issues)
    {
        switch (opType)
        {
            case "Move":
            case "Rename":
            {
                // oldValue / newValue are FULL PATHS for both ops as of v2.2.0
                if (!string.IsNullOrEmpty(newValue) && FindAllNodesAtPath(root, newValue).Count == 0)
                    issues.Add($"OUTCOME MISMATCH: expected {opType} to leave something resolvable at " +
                               $"'{EEMPath.ToVrcf(newValue)}', but nothing resolves there. Check rawMoveMenuItemRecords.");
                if (!string.IsNullOrEmpty(oldValue) && !EEMPath.PathEq(oldValue, newValue) &&
                    FindAllNodesAtPath(root, oldValue).Count >=
                        (context != null && context.TryGetValue("previousMatchCount", out var count) && count is int previous
                            ? System.Math.Max(1, previous) : 1))
                    issues.Add($"OUTCOME MISMATCH: expected '{EEMPath.ToVrcf(oldValue)}' to no longer resolve after " +
                               $"{opType}, but it still does. Regenerated by: {DescribeGenerators(oldValue)}");
                break;
            }

            case "Delete":
            case "BulkDelete":
                if (context != null && context.TryGetValue("expectedDeleteCounts", out var deleteValue) && deleteValue is List<object> deleteCounts)
                {
                    foreach (var count in deleteCounts.OfType<Dictionary<string, object>>())
                    {
                        string path = count["path"] as string;
                        int maximum = (int)count["maximumCount"];
                        int remaining = FindAllNodesAtPath(root, path).Count;
                        if (remaining > maximum)
                            issues.Add($"OUTCOME MISMATCH: expected at most {maximum} item(s) at '{EEMPath.ToVrcf(path)}' after {opType}, but {remaining} remain.");
                    }
                    break;
                }
                foreach (var p in (oldValue ?? "").Split(new[] { ", " }, System.StringSplitOptions.RemoveEmptyEntries))
                {
                    // NodeByPath now returns null both for "nothing here" and for
                    // "genuinely ambiguous" — the wrong tool for an existence
                    // check. FindAllNodesAtPath answers "does anything at all
                    // still resolve here", which is what this is actually asking.
                    var survivors = FindAllNodesAtPath(root, p);
                    if (survivors.Count == 0) continue;
                    var survivor = survivors[0];
                    int survivingDescendants = survivors.Sum(s => CollectAllDescendants(s).Count);
                    string scope = survivingDescendants > 0
                        ? $"and still has {survivingDescendants} item(s) inside it — this was not a harmless empty container"
                        : "as an empty container";
                    issues.Add($"OUTCOME MISMATCH: expected '{EEMPath.ToVrcf(p)}' to be deleted, but it still " +
                               $"resolves {scope}. Regenerated by: {DescribeGenerators(p)}");
                }
                break;

            case "BulkMove":
            {
                string dest = newValue ?? "";
                var expectedPaths = context != null && context.TryGetValue("expectedPaths", out var expectedValues) &&
                    expectedValues is List<object> paths
                    ? paths.OfType<string>().ToList()
                    : (oldValue ?? "").Split(new[] { ", " }, System.StringSplitOptions.RemoveEmptyEntries)
                        .Select(p => EEMPath.Combine(dest, EEMPath.LeafOf(p))).ToList();
                foreach (var expected in expectedPaths)
                {
                    string leaf = EEMPath.LeafOf(expected);
                    if (FindAllNodesAtPath(root, expected).Count == 0)
                        issues.Add($"OUTCOME MISMATCH: expected '{EEMPath.ToVrcf(leaf)}' at " +
                                   $"'{EEMPath.ToVrcf(expected)}' after BulkMove, but nothing resolves there.");
                }
                if (context != null && context.TryGetValue("expectedBlankCounts", out var blankValues) && blankValues is List<object> blankCounts)
                {
                    foreach (var value in blankCounts.OfType<Dictionary<string, object>>())
                    {
                        string path = value["path"] as string;
                        bool foldersOnly = (bool)value["foldersOnly"];
                        int minimumCount = (int)value["minimumCount"];
                        int actualCount = FindAllNodesAtPath(root, path).Count(n => n.IsFolderLike == foldersOnly);
                        if (actualCount < minimumCount)
                            issues.Add($"OUTCOME MISMATCH: expected at least {minimumCount} unnamed " +
                                $"{(foldersOnly ? "submenus" : "controls")} at '{EEMPath.ToVrcf(EEMPath.ParentPath(path))}' " +
                                $"after BulkMove, but only {actualCount} remain. Items may have merged or been missed.");
                    }
                }
                break;
            }

            case "Create":
                if (!string.IsNullOrEmpty(newValue) && NodeByPath(root, EEMPath.FromVrcf(newValue)) == null)
                    issues.Add($"OUTCOME MISMATCH: expected a new item at '{newValue}', but nothing resolves there.");
                break;

            case "Duplicate":
            {
                var duplicates = FindAllNodesAtPath(root, newValue);
                int previousMatches = context != null && context.TryGetValue("previousMatchCount", out var previousValue) && previousValue is int countBefore
                    ? countBefore : 0;
                if (duplicates.Count <= previousMatches)
                {
                    issues.Add($"OUTCOME MISMATCH: expected an additional item at '{EEMPath.ToVrcf(newValue)}' after Duplicate, but none was added.");
                    break;
                }
                int previousPopulated = context != null && context.TryGetValue("previousPopulatedMatchCount", out var populatedValue) && populatedValue is int populatedBefore
                    ? populatedBefore : 0;
                if (context != null && context.TryGetValue("childCountBefore", out var cb) && cb is int before &&
                    before > 0 && duplicates.Count(dup => dup.children.Count > 0) <= previousPopulated)
                    issues.Add($"EMPTY DUPLICATE: source had {before} child item(s) but the duplicate has none.");
                break;
            }

            case "IconChange":
            case "BulkIcon":
            {
                if (context != null && context.TryGetValue("expectedIconTargets", out var targetsValue) && targetsValue is List<object> iconTargets)
                {
                    int wantedId = (int)context["expectedIconId"];
                    foreach (var target in iconTargets.OfType<Dictionary<string, object>>())
                    {
                        string key = target["stableKey"] as string;
                        string path = target["path"] as string;
                        var live = allNodesFlatList.FirstOrDefault(n => n.stableKey == key);
                        if (live == null)
                        {
                            issues.Add($"OUTCOME MISMATCH: selected control '{EEMPath.ToVrcf(path)}' vanished during {opType}.");
                            continue;
                        }
                        int actualId = live.icon ? live.icon.GetInstanceID() : 0;
                        if (actualId != wantedId)
                            issues.Add($"OUTCOME MISMATCH: expected icon '{newValue}' on selected control '{EEMPath.ToVrcf(path)}' but found '{(live.icon ? live.icon.name : "(none)")}'.");
                    }
                    break;
                }
                var iconPaths = opType == "IconChange" ? new[] { targetPath } :
                    (targetPath ?? "").Split(new[] { ", " }, System.StringSplitOptions.RemoveEmptyEntries);
                foreach (var path in iconPaths)
                {
                    var matches = FindAllNodesAtPath(root, path);
                    if (matches.Count == 0)
                    {
                        issues.Add($"OUTCOME MISMATCH: '{EEMPath.ToVrcf(path)}' vanished during {opType}.");
                        continue;
                    }
                    if (matches.Count > 1)
                    {
                        issues.Add($"OUTCOME MISMATCH: can't identify the selected control at ambiguous path '{EEMPath.ToVrcf(path)}' during {opType} without its source key.");
                        continue;
                    }
                    string actual = matches[0].icon ? matches[0].icon.name : "(none)";
                    if (!string.Equals(actual, newValue))
                        issues.Add($"OUTCOME MISMATCH: expected icon '{newValue}' on '{EEMPath.ToVrcf(path)}' but found '{actual}'.");
                }
                break;
            }

            case "Restore":
            {
                if (context != null && context.TryGetValue("problems", out var pr) && pr is List<object> list && list.Count > 0)
                    foreach (var p in list) issues.Add("RESTORE INCOMPLETE: " + p);
                break;
            }

            case "StructureImport":
            {
                if (context != null && context.TryGetValue("problems", out var pr) && pr is List<object> list && list.Count > 0)
                    foreach (var p in list) issues.Add("IMPORT SKIPPED: " + p);
                break;
            }
        }
    }

    /// Names the thing keeping a path alive. Without this the "still resolves"
    /// message is true but useless — you cannot tell a failed delete from a
    /// successful delete that something immediately re-created.
    string DescribeGenerators(string internalPath)
    {
        var reasons = new List<string>();

        if (virtualFolderPaths.Any(p => EEMPath.IsAtOrUnder(p, internalPath)))
            reasons.Add("virtual menu store entry");

        foreach (var r in ReadMoveRecords())
        {
            if (EEMPath.IsAtOrUnder(r.to, internalPath))
                reasons.Add($"MoveMenuItem toPath '{EEMPath.ToVrcf(r.to)}'");
            else if (EEMPath.IsAtOrUnder(r.from, internalPath))
                reasons.Add($"MoveMenuItem fromPath '{EEMPath.ToVrcf(r.from)}'");
        }

        var node = NodeByPath(root, internalPath);
        if (node != null)
        {
            if (node.isFCPrefixFolder) reasons.Add("Full Controller entry prefix");
            if (node.sourceObject != null) reasons.Add("a VRCFury toggle whose content.name still points here");
            if (node.sourceControl != null && node.sourceMenu != null) reasons.Add("a native VRC menu control");
            if (node.isFromFullController) reasons.Add("a Full Controller menu control");
            if (reasons.Count == 0 && node.children.Count > 0)
                reasons.Add($"{node.children.Count} surviving child item(s)");
        }

        return reasons.Count == 0 ? "nothing obvious — the delete itself may have failed"
                                  : string.Join(", ", reasons.Distinct());
    }

}
